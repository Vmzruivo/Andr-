import fs from 'node:fs';
const file='scripts/patch-goals.mjs';
let s=fs.readFileSync(file,'utf8');
const start=s.indexOf('const helpers=`');
const end=s.indexOf('`.replaceAll',start);
if(start<0||end<0) throw new Error('Goal helpers template not found');
const before=s.slice(0,start+15);
let inner=s.slice(start+15,end);
inner=inner.replaceAll('setMissionNotice(__DOLLAR__`Objetivo concluído: +__DOLLAR__{obj.xp} XP. Continue sua meta!`);','setMissionNotice("Objetivo concluído: +"+obj.xp+" XP. Continue sua meta!");');
inner=inner.replaceAll('__DOLLAR__`','`');
inner=inner.replaceAll('__DOLLAR__{','\\${');
inner=inner.replaceAll('`','\\`');
const after=s.slice(end);
s=before+inner+after;
fs.writeFileSync(file,s);
